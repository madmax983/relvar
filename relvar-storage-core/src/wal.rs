//! Log Sequence Numbers, transaction IDs, WAL records, and WAL framing.
//!
//! Moved from `relvar-storage`'s `wal/lsn.rs` and `wal/record.rs` into the
//! `no_std` storage core, adapting `std::` paths to `core::`/`alloc::`.
//! Two deliberate deviations from a verbatim move:
//!
//! * `WalRecord::Checkpoint.dirty_pages` uses [`hashbrown::HashMap`] instead
//!   of `std::collections::HashMap` (`std` is unavailable without the `std`
//!   feature). The postcard map encoding (varint length + entries) is
//!   unchanged, so on-disk bytes keep the same format.
//! * `Lsn::next`'s overflow path is spelled as an explicit `match` +
//!   `panic!` rather than `.expect()` — same message, same behavior —
//!   because the house rules forbid `.expect()` in non-test code.
//!
//! # WAL framing
//!
//! This module additionally defines the v0.7 WAL frame format. A v0.7 WAL
//! file is laid out as:
//!
//! ```text
//! [magic: 8 bytes][frame][frame]...
//! ```
//!
//! where `magic` is [`WAL_MAGIC_V2`] (`b"RELVAR02"`), and each frame is:
//!
//! ```text
//! [lsn: u64 LE][payload_len: u64 LE][postcard payload][crc32: u32 LE]
//! ```
//!
//! `payload_len` covers **only** the postcard bytes. The CRC-32 (IEEE,
//! [`crate::crc::crc32`]) covers `lsn` + `payload_len` + payload, so a torn
//! write — a partial frame at the tail — fails CRC verification instead of
//! decoding silently.
//!
//! Pre-v0.7 WAL files have **no** file magic and no CRC; their frames are
//! `[lsn: u64 LE][payload_len: u64 LE][postcard payload]`. Use
//! [`decode_legacy_frames`] to read those. Both decoders operate on the byte
//! stream *after* any file magic.
//!
//! # TTM Compliance
//!
//! Per Proscription 6, log records use relation names and serialized tuple
//! data, never physical TupleId values. This maintains physical data
//! independence — the logical layer has no knowledge of physical storage.

use crate::crc::crc32;
use alloc::string::String;
use alloc::vec::Vec;
use core::fmt;
use core::sync::atomic::{AtomicU64, Ordering};
use hashbrown::HashMap;
use serde::{Deserialize, Serialize};
use thiserror::Error;

