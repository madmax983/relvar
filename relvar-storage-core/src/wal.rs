    fn test_frame_layout_is_exact() {
        let record = WalRecord::Begin {
            txn_id: TransactionId::new(9),
        };
        let payload = record.serialize().unwrap();
        let frame = encode_frame(Lsn::new(0x0102_0304_0506_0708), &record).unwrap();

        // [lsn:8 LE][payload_len:8 LE][payload][crc32:4 LE]
        assert_eq!(frame.len(), 8 + 8 + payload.len() + 4);
        assert_eq!(
            u64::from_le_bytes(frame[0..8].try_into().unwrap()),
            0x0102_0304_0506_0708
        );
        assert_eq!(
            u64::from_le_bytes(frame[8..16].try_into().unwrap()),
            payload.len() as u64,
            "payload_len must cover only the postcard bytes"
        );
        assert_eq!(&frame[16..16 + payload.len()], payload.as_slice());

        // CRC covers lsn_bytes + len_bytes + payload.
        let expected_crc = crc32(&frame[..16 + payload.len()]);
        let stored_crc = u32::from_le_bytes(frame[16 + payload.len()..].try_into().unwrap());
        assert_eq!(stored_crc, expected_crc);
    }

