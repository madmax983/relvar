/// File magic identifying a v0.7 WAL file with legacy (pre-CRC) framing.
///
/// Pre-v0.7 WAL files carry no file magic at all; this constant exists so a
/// v0.7 writer can explicitly label a file that uses the legacy
/// `[lsn][len][postcard]` frame layout (readable via
/// [`decode_legacy_frames`]).
pub const WAL_MAGIC_V1: &[u8; 8] = b"RELVAR01";

/// File magic identifying a v0.7 WAL file with CRC-32 frame framing.
///
/// A v0.7 WAL file starts with these 8 bytes, followed by frames as produced
/// by [`encode_frame`] and readable via [`decode_frames`].
pub const WAL_MAGIC_V2: &[u8; 8] = b"RELVAR02";

/// Errors that can occur during WAL frame encoding/decoding.
///
/// Core-only: no `std::io::Error` variant — I/O failures belong to the
/// [`crate::device::BlockDevice`] implementation on the host side.
#[derive(Debug, Error)]
pub enum WalError {
    /// A WAL record failed to serialize or deserialize.
    #[error("WAL record error: {0}")]
    Record(#[from] WalRecordError),

    /// Frame CRC-32 mismatch: the frame was torn or corrupted.
    ///
    /// A CRC mismatch is always reported as an error, never silently
    /// accepted — this is the torn-write detection.
    #[error(
        "CRC mismatch in WAL frame at offset {offset}: expected {expected:#010x}, computed {actual:#010x}"
    )]
    CrcMismatch {
        /// Byte offset of the frame within the decoded buffer.
        offset: usize,
        /// CRC-32 stored at the end of the frame.
        expected: u32,
        /// CRC-32 computed over the frame's headers + payload.
        actual: u32,
    },

    /// The buffer ends mid-frame: a torn write at the tail.
    #[error("Truncated WAL frame at offset {0}")]
    Truncated(usize),

    /// The frame's declared payload length exceeds [`MAX_RECORD_SIZE`].
    #[error("WAL frame payload length {0} exceeds maximum record size")]
    PayloadTooLarge(u64),
}

/// Encodes a WAL record as a v2 frame.
///
/// Frame layout: `[lsn: u64 LE][payload_len: u64 LE][postcard payload][crc32: u32 LE]`.
/// `payload_len` covers only the postcard bytes; the CRC-32 (IEEE) covers
/// `lsn` + `payload_len` + payload.
///
/// # Errors
///
/// Returns [`WalError::Record`] if the record cannot be serialized or
/// exceeds [`MAX_RECORD_SIZE`].
///
/// # Examples
///
/// ```
/// use relvar_storage_core::wal::{Lsn, TransactionId, WalRecord, decode_frames, encode_frame};
///
/// let record = WalRecord::Begin { txn_id: TransactionId::new(1) };
/// let frame = encode_frame(Lsn::new(7), &record).unwrap();
///
/// let decoded: Vec<_> = decode_frames(&frame).collect();
/// assert_eq!(decoded.len(), 1);
/// let (lsn, decoded_record) = decoded.into_iter().next().unwrap().unwrap();
/// assert_eq!(lsn, Lsn::new(7));
/// assert_eq!(decoded_record, record);
/// ```
pub fn encode_frame(lsn: Lsn, record: &WalRecord) -> Result<Vec<u8>, WalError> {
    let payload = record.serialize()?;

    let mut frame = Vec::with_capacity(8 + 8 + payload.len() + 4);
    frame.extend_from_slice(&lsn.value().to_le_bytes());
    frame.extend_from_slice(&(payload.len() as u64).to_le_bytes());
    frame.extend_from_slice(&payload);
    // CRC covers lsn_bytes + len_bytes + payload (everything so far).
    let checksum = crc32(&frame);
    frame.extend_from_slice(&checksum.to_le_bytes());
    Ok(frame)
}

/// Reads a little-endian `u64` at `offset`, or `None` if out of bounds.
fn read_u64_le(data: &[u8], offset: usize) -> Option<u64> {
    let bytes: [u8; 8] = data.get(offset..offset + 8)?.try_into().ok()?;
    Some(u64::from_le_bytes(bytes))
}

/// Reads a little-endian `u32` at `offset`, or `None` if out of bounds.
fn read_u32_le(data: &[u8], offset: usize) -> Option<u32> {
    let bytes: [u8; 4] = data.get(offset..offset + 4)?.try_into().ok()?;
    Some(u32::from_le_bytes(bytes))
}

/// Iterator over v2 WAL frames in a byte buffer.
///
/// Yields `Ok((Lsn, WalRecord))` per frame. The first corrupt frame yields
/// an `Err` and then the iterator stops: a torn or corrupted frame means
/// every byte after it is suspect, so recovery must not continue past it.
/// An empty tail (offset exactly at end of buffer) is a clean end and
/// yields `None`.
pub struct FrameDecoder<'a> {
    data: &'a [u8],
    offset: usize,
    failed: bool,
}

impl<'a> FrameDecoder<'a> {
    /// Creates a decoder over `data` (the byte stream after any file magic).
    fn new(data: &'a [u8]) -> Self {
        Self {
            data,
            offset: 0,
            failed: false,
        }
    }
}

impl Iterator for FrameDecoder<'_> {
    type Item = Result<(Lsn, WalRecord), WalError>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.failed {
            return None;
        }
        // After the first error the iterator is fused: report the error once,
        // then stop.
        let fail = |decoder: &mut Self, error: WalError| {
            decoder.failed = true;
            Some(Err(error))
        };

        let offset = self.offset;
        if offset == self.data.len() {
            return None; // Clean end of stream.
        }

        let lsn_value = match read_u64_le(self.data, offset) {
            Some(value) => value,
            None => return fail(self, WalError::Truncated(offset)),
        };
        let payload_len_u64 = match read_u64_le(self.data, offset + 8) {
            Some(value) => value,
            None => return fail(self, WalError::Truncated(offset)),
        };
        if payload_len_u64 > MAX_RECORD_SIZE as u64 {
            return fail(self, WalError::PayloadTooLarge(payload_len_u64));
        }
        let payload_len = match usize::try_from(payload_len_u64) {
            Ok(len) => len,
            Err(_) => return fail(self, WalError::PayloadTooLarge(payload_len_u64)),
        };

        let payload_end = match (offset + 16).checked_add(payload_len) {
            Some(end) => end,
            None => return fail(self, WalError::Truncated(offset)),
        };
        let frame_end = match payload_end.checked_add(4) {
            Some(end) => end,
            None => return fail(self, WalError::Truncated(offset)),
        };
        if frame_end > self.data.len() {
            // Torn write: the frame's bytes never fully landed.
            return fail(self, WalError::Truncated(offset));
        }

        let expected = match read_u32_le(self.data, payload_end) {
            Some(value) => value,
            None => return fail(self, WalError::Truncated(offset)),
        };
        let actual = crc32(&self.data[offset..payload_end]);
        if expected != actual {
            return fail(
                self,
                WalError::CrcMismatch {
                    offset,
                    expected,
                    actual,
                },
            );
        }

        let record = match WalRecord::deserialize(&self.data[offset + 16..payload_end]) {
            Ok(record) => record,
            Err(error) => return fail(self, WalError::Record(error)),
        };

        self.offset = frame_end;
        Some(Ok((Lsn::new(lsn_value), record)))
    }
}

/// Decodes v2 WAL frames from a byte buffer.
///
/// Each frame is verified with CRC-32; a torn or corrupted frame yields an
/// error (never a silent mis-decode) and stops the iterator. Operates on
/// the byte stream *after* any 8-byte file magic.
///
/// # Examples
///
/// ```
/// use relvar_storage_core::wal::{Lsn, TransactionId, WalRecord, decode_frames, encode_frame};
///
/// let frames: Vec<u8> = [1u64, 2, 3]
///     .into_iter()
///     .flat_map(|i| {
///         encode_frame(
///             Lsn::new(i),
///             &WalRecord::Commit { txn_id: TransactionId::new(i) },
///         )
///         .unwrap()
///     })
///     .collect();
///
/// let decoded: Vec<_> = decode_frames(&frames)
///     .collect::<Result<_, _>>()
///     .unwrap();
/// assert_eq!(decoded.len(), 3);
/// assert_eq!(decoded[0].0, Lsn::new(1));
/// ```
pub fn decode_frames(data: &[u8]) -> FrameDecoder<'_> {
    FrameDecoder::new(data)
}

/// Iterator over legacy (pre-v0.7) WAL frames in a byte buffer.
///
/// Legacy frames are `[lsn: u64 LE][payload_len: u64 LE][postcard payload]`
/// with no CRC and no file magic. A buffer shorter than the 16-byte header
/// is treated as a clean end; a frame that extends past the buffer yields
/// an error and stops the iterator (mirroring the old recovery behavior of
/// treating a torn tail as the end of the valid log).
pub struct LegacyFrameDecoder<'a> {
    data: &'a [u8],
    offset: usize,
    failed: bool,
}

impl<'a> LegacyFrameDecoder<'a> {
    /// Creates a decoder over `data` (the raw legacy WAL bytes).
    fn new(data: &'a [u8]) -> Self {
        Self {
            data,
            offset: 0,
            failed: false,
        }
    }
}

impl Iterator for LegacyFrameDecoder<'_> {
    type Item = Result<(Lsn, WalRecord), WalError>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.failed {
            return None;
        }
        let fail = |decoder: &mut Self, error: WalError| {
            decoder.failed = true;
            Some(Err(error))
        };

        let offset = self.offset;
        // Need at least 16 bytes for LSN (8) + length (8); a short tail is a
        // clean end (torn header bytes simply never landed).
        if offset + 16 > self.data.len() {
            return None;
        }

        let lsn_value = match read_u64_le(self.data, offset) {
            Some(value) => value,
            None => return fail(self, WalError::Truncated(offset)),
        };
        let payload_len_u64 = match read_u64_le(self.data, offset + 8) {
            Some(value) => value,
            None => return fail(self, WalError::Truncated(offset)),
        };
        if payload_len_u64 > MAX_RECORD_SIZE as u64 {
            return fail(self, WalError::PayloadTooLarge(payload_len_u64));
        }
        let payload_len = match usize::try_from(payload_len_u64) {
            Ok(len) => len,
            Err(_) => return fail(self, WalError::PayloadTooLarge(payload_len_u64)),
        };

        let payload_end = match (offset + 16).checked_add(payload_len) {
            Some(end) => end,
            None => return fail(self, WalError::Truncated(offset)),
        };
        if payload_end > self.data.len() {
            // Torn tail: the old recovery code surfaced this as corruption
            // and stopped the scan at the last valid record.
            return fail(self, WalError::Truncated(offset));
        }

        let record = match WalRecord::deserialize(&self.data[offset + 16..payload_end]) {
            Ok(record) => record,
            Err(error) => return fail(self, WalError::Record(error)),
        };

        self.offset = payload_end;
        Some(Ok((Lsn::new(lsn_value), record)))
    }
}

/// Decodes legacy (pre-v0.7) WAL frames from a byte buffer.
///
/// Legacy format: `[lsn: u64 LE][payload_len: u64 LE][postcard payload]`,
/// no CRC, no file magic. This is the read path for WAL files written
/// before v0.7.
pub fn decode_legacy_frames(data: &[u8]) -> LegacyFrameDecoder<'_> {
    LegacyFrameDecoder::new(data)
}

