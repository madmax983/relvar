/// Log Sequence Number — uniquely identifies a position in the WAL.
///
/// LSNs are monotonically increasing and provide a total ordering of
/// all log records. They are used to determine which operations happened
/// before others during recovery.
///
/// # Examples
///
/// ```ignore
/// use relvar_storage_core::wal::Lsn;
///
/// let lsn1 = Lsn::new(1);
/// let lsn2 = Lsn::new(2);
///
/// assert!(lsn1 < lsn2);
/// assert_eq!(lsn1.next(), lsn2);
/// ```ignore
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct Lsn(u64);

/// Unique identifier for a transaction.
///
/// TransactionIds are generated by [`TransactionIdGenerator`] and uniquely
/// identify a transaction within the database. They are separate from LSNs
/// because a single transaction may generate multiple log records.
///
/// # Examples
///
/// ```ignore
/// use relvar_storage_core::wal::TransactionId;
///
/// let txn1 = TransactionId::new(1);
/// let txn2 = TransactionId::new(2);
///
/// assert_ne!(txn1, txn2);
/// ```ignore
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct TransactionId(u64);

/// Generates unique transaction IDs using atomic operations.
///
/// This generator is thread-safe and guarantees that each transaction
/// receives a unique identifier.
pub struct TransactionIdGenerator {
    next_id: AtomicU64,
}

impl Lsn {
    /// Creates a new LSN with the given value.
    ///
    /// # Examples
    /// ```ignore
    /// use relvar_storage_core::wal::Lsn;
    /// let lsn = Lsn::new(42);
    /// assert_eq!(lsn.value(), 42);
    /// ```ignore
    pub fn new(value: u64) -> Self {
        Self(value)
    }

    /// Generates and provides the next sequential LSN.
    ///
    /// # Panics
    ///
    /// Panics on `u64` overflow, which is unrecoverable (and unreachable in
    /// practice — it would require 2⁶⁴ log records).
    ///
    /// # Examples
    ///
    /// ```ignore
    /// use relvar_storage_core::wal::Lsn;
    ///
    /// let lsn = Lsn::new(42);
    /// assert_eq!(lsn.next(), Lsn::new(43));
    /// ```ignore
    pub fn next(self) -> Self {
        // Spelled without `.expect()`: same message and behavior, but the
        // house rules forbid `.expect()` in non-test code.
        match self.0.checked_add(1) {
            Some(value) => Self(value),
            None => panic!("LSN overflow"),
        }
    }

    /// Extracts the raw numerical value of this `Lsn`.
    ///
    /// This is typically used when serializing the LSN into page headers or WAL records.
    ///
    /// # Examples
    ///
    /// ```ignore
    /// use relvar_storage_core::wal::Lsn;
    ///
    /// let lsn = Lsn::new(42);
    /// assert_eq!(lsn.value(), 42);
    /// ```ignore
    pub fn value(self) -> u64 {
        self.0
    }
}

impl TransactionId {
    /// Creates a new TransactionId with the given value.
    ///
    /// # Examples
    /// ```ignore
    /// use relvar_storage_core::wal::TransactionId;
    /// let txn = TransactionId::new(100);
    /// assert_eq!(txn.value(), 100);
    /// ```ignore
    pub fn new(value: u64) -> Self {
        Self(value)
    }

    /// Extracts the raw numerical value of this `TransactionId`.
    ///
    /// This is commonly used during serialization or when logging transaction details.
    ///
    /// # Examples
    ///
    /// ```ignore
    /// use relvar_storage_core::wal::TransactionId;
    ///
    /// let txn = TransactionId::new(100);
    /// assert_eq!(txn.value(), 100);
    /// ```ignore
    pub fn value(self) -> u64 {
        self.0
    }
}

impl TransactionIdGenerator {
    /// Creates a new transaction ID generator starting from 1.
    ///
    /// # Examples
    /// ```ignore
    /// use relvar_storage_core::wal::TransactionIdGenerator;
    /// let generator = TransactionIdGenerator::new();
    /// assert_eq!(generator.generate().value(), 1);
    /// ```ignore
    pub fn new() -> Self {
        Self {
            next_id: AtomicU64::new(1),
        }
    }

    /// Creates a new transaction ID generator starting from a specific ID.
    ///
    /// Used during recovery to continue from the maximum transaction ID
    /// seen in the WAL, preventing ID reuse.
    ///
    /// # Examples
    /// ```ignore
    /// use relvar_storage_core::wal::{TransactionId, TransactionIdGenerator};
    /// let generator = TransactionIdGenerator::from_start(TransactionId::new(50));
    /// assert_eq!(generator.generate().value(), 50);
    /// ```ignore
    pub fn from_start(start_id: TransactionId) -> Self {
        Self {
            next_id: AtomicU64::new(start_id.value()),
        }
    }

    /// Generates the next unique transaction ID.
    ///
    /// This method is thread-safe and guarantees uniqueness.
    ///
    /// # Panics
    ///
    /// Panics on `u64` overflow, which is unrecoverable.
    ///
    /// # Examples
    /// ```ignore
    /// use relvar_storage_core::wal::TransactionIdGenerator;
    /// let generator = TransactionIdGenerator::new();
    /// let txn_id = generator.generate();
    /// assert_eq!(txn_id.value(), 1);
    /// ```ignore
    pub fn generate(&self) -> TransactionId {
        let id = self.next_id.fetch_add(1, Ordering::SeqCst);
        if id == u64::MAX {
            panic!("TransactionId overflow");
        }
        TransactionId(id)
    }

    /// Peeks at the next transaction ID without consuming it.
    ///
    /// This is the MVCC visibility horizon: every transaction that has begun
    /// so far holds an ID strictly less than the peeked value, so a snapshot
    /// stamped with this horizon hides versions created by transactions that
    /// begin afterwards — even if those transactions commit before the
    /// snapshot is read. This is what makes Repeatable Read actually repeat.
    pub fn peek_next(&self) -> TransactionId {
        TransactionId(self.next_id.load(Ordering::SeqCst))
    }
}

impl Default for TransactionIdGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Display for Lsn {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "LSN({})", self.0)
    }
}

impl fmt::Display for TransactionId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "TXN({})", self.0)
    }
}

